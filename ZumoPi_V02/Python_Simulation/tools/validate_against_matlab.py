"""
Compare the Python simulation with reference runs exported from the original
Simulink models (reference_data/ref_*.mat, generated by tools/matlab/runRef.m).

    python tools/validate_against_matlab.py          # prints a table + saves plots
"""
import os
import sys
import numpy as np
import scipy.io as sio
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from zumo_sim import ZumoParams, simulate  # noqa: E402

REF = os.path.join(ROOT, "reference_data")
OUT = os.path.join(ROOT, "validation")


def load(name):
    S = sio.loadmat(os.path.join(REF, name), squeeze_me=True)
    g = lambda k: np.atleast_1d(S[k])
    ctrl = "PathControl" if "Path_Control" in name else "PointToPointControl"
    return {
        "t": g("EncoderPositionEstimation_1_t"),
        "x": g("EncoderPositionEstimation_1"),
        "y": g("EncoderPositionEstimation_2"),
        "phi": g("EncoderPositionEstimation_3"),
        "v": g("Saturation_1"),
        "theta": g(f"{ctrl}_2"),
        "wl": g("DCMotorSimulationLeft_1"),
        "wr": g("DCMotorSimulationRight_1"),
        "ul": g("DiscretePIDController_1"),
        "pts": np.atleast_2d(S["pts"]),
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    cases = [("Path_Control", "path", 1.0), ("P2P_MultiPoint", "p2p", 2.0)]
    rows = []
    for shape in ["line", "square", "inf"]:
        fig, ax = plt.subplots(1, 3, figsize=(16, 5))
        for mdl, mode, decel in cases:
            ref = load(f"ref_{mdl}_{shape}.mat")
            T = ref["t"][-1]
            p = ZumoParams(sim_time=T, decel_factor=decel)
            r = simulate(ref["pts"], mode, p, stop_when_done=False)
            n = min(len(r.t), len(ref["t"]))
            pos_py = np.column_stack([r.x[:n], r.y[:n]])
            pos_ml = np.column_stack([ref["x"][:n], ref["y"][:n]])
            dpos = np.linalg.norm(pos_py - pos_ml, axis=1)
            dphi = np.degrees(np.abs(r.phi[:n] - ref["phi"][:n]))
            # time at which each run stops moving
            def stop_t(t, x, y):
                v = np.hypot(np.diff(x), np.diff(y))
                idx = np.nonzero(v > 1e-6)[0]
                return t[idx[-1]] if len(idx) else 0
            rows.append((shape, mode, dpos.max() * 1000, np.sqrt(np.mean(dpos ** 2)) * 1000,
                         dphi.max(), np.linalg.norm(pos_py[-1] - pos_ml[-1]) * 1000,
                         stop_t(ref["t"], ref["x"], ref["y"]), stop_t(r.t, r.x, r.y)))

            ax[0].plot(ref["x"], ref["y"], lw=2.5, alpha=0.5, label=f"MATLAB {mode}")
            ax[0].plot(r.x, r.y, "--", lw=1.2, label=f"Python {mode}")
            ax[1].plot(ref["t"], np.degrees(ref["phi"]), lw=2.5, alpha=0.5, label=f"MATLAB {mode}")
            ax[1].plot(r.t, np.degrees(r.phi), "--", lw=1.2, label=f"Python {mode}")
            ax[2].plot(ref["t"], ref["wl"], lw=2.5, alpha=0.5, label=f"MATLAB {mode} wL")
            ax[2].plot(r.t, r.wl, "--", lw=1.2, label=f"Python {mode} wL")
        pts = ref["pts"]
        ax[0].plot(pts[:, 0], pts[:, 1], "k*", label="way-points")
        ax[0].set_aspect("equal"); ax[0].grid(True); ax[0].legend(fontsize=8)
        ax[0].set_title(f"{shape}: X-Y"); ax[0].set_xlabel("X [m]"); ax[0].set_ylabel("Y [m]")
        ax[1].grid(True); ax[1].set_title("Heading Phi [deg]"); ax[1].set_xlabel("t [s]"); ax[1].legend(fontsize=8)
        ax[2].grid(True); ax[2].set_title("Left wheel speed (encoder)"); ax[2].set_xlabel("t [s]"); ax[2].legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(os.path.join(OUT, f"validation_{shape}.png"), dpi=110)
        plt.close(fig)

    hdr = f"{'path':8s}{'mode':6s}{'max dPos[mm]':>14s}{'rms dPos[mm]':>14s}{'max dPhi[deg]':>15s}{'final dPos[mm]':>16s}{'stop t ML':>11s}{'stop t PY':>11s}"
    print(hdr)
    for r in rows:
        print(f"{r[0]:8s}{r[1]:6s}{r[2]:14.1f}{r[3]:14.1f}{r[4]:15.2f}{r[5]:16.1f}{r[6]:11.2f}{r[7]:11.2f}")
    print(f"\nplots saved to {OUT}")


if __name__ == "__main__":
    main()
